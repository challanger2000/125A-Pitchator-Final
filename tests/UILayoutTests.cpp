// 125A Pitchator: source-of-truth geometrical UI audit (100% and 150%).
// Test intentionally fails on clipping, inconsistent baselines and text width.
#include <algorithm>
#include <cmath>
#include <cstdio>
#include <fstream>
#include <iterator>
#include <map>
#include <regex>
#include <string>
#include <vector>
#include <cstdlib>
struct Rect {double x=0,y=0,w=0,h=0;};
struct Node {std::string cls,tag,id,title,font,align,transparent;Rect rect;int parent=-1;};
#define CHECK(x) do{if(!(x)){std::fprintf(stderr,"UILayout line %d: %s\n",__LINE__,#x);return 1;}}while(0)
static std::string load(const char* path){
 std::ifstream file(path,std::ios::binary);
 return {std::istreambuf_iterator<char>(file),std::istreambuf_iterator<char>()};
}
static std::string attr(const std::string& s,const std::string& key){
 const std::regex re("(?:^|\\s)"+key+"=\"([^\"]*)\"");
 std::smatch m;
 return std::regex_search(s,m,re)?m[1].str():"";
}
static Rect parseRect(const std::string& origin,const std::string& size){
 Rect r{};
 if(std::sscanf(origin.c_str(),"%lf, %lf",&r.x,&r.y)!=2||
    std::sscanf(size.c_str(),"%lf, %lf",&r.w,&r.h)!=2)return {};
 return r;
}
static Rect absolute(const std::vector<Node>& nodes,size_t i){
 Rect r=nodes[i].rect;
 int parent=nodes[i].parent;
 while(parent>=0){
  r.x+=nodes[static_cast<size_t>(parent)].rect.x;
  r.y+=nodes[static_cast<size_t>(parent)].rect.y;
  parent=nodes[static_cast<size_t>(parent)].parent;
 }
 return r;
}
static bool collides(const Rect& a,const Rect& b){
 return a.x<b.x+b.w&&b.x<a.x+a.w&&a.y<b.y+b.h&&b.y<a.y+a.h;
}
int main(){
 const std::string xml=load(PITCHATOR_UIDESC_PATH);
 const std::string logo=load(PITCHATOR_LOGO_SRC_PATH);
 const std::string factory=load(PITCHATOR_SRC_PATH);
 CHECK(!xml.empty()&&!logo.empty()&&!factory.empty());
 CHECK(xml.find("size=\"1200, 620\"")!=std::string::npos);
 CHECK(xml.find("minSize=\"1200, 620\"")!=std::string::npos);
 CHECK(xml.find("maxSize=\"1800, 930\"")!=std::string::npos);
 // Do not accept handwritten logo approximations. Must reference the
 // direct source-of-truth vector data regenerated from the official master.
 CHECK(logo.find("AUTOGENERATED from challanger2000/125A-Branding/125A_Logo_Master_FINAL.svg")!=std::string::npos);
 CHECK(logo.find("kPathFilledEvenOdd")!=std::string::npos);
 CHECK(logo.find("kLogoCommands[]")!=std::string::npos);
 CHECK(logo.find("kLogoShapes[]")!=std::string::npos);
 CHECK(factory.find("new pitchator::BrandLogoView(view->getViewSize())")!=std::string::npos);
 std::vector<Node> nodes;
 std::vector<int> stack;
 const std::regex viewRe(R"(<(/?)view\b([^>]*?)>)");
 for(auto it=std::sregex_iterator(xml.begin(),xml.end(),viewRe);
     it!=std::sregex_iterator();++it){
  const std::string closing=(*it)[1].str(), a=(*it)[2].str();
  if(closing=="/"){CHECK(!stack.empty());stack.pop_back();continue;}
  const std::string s=a;
  Node n;
  n.cls=attr(s,"class");n.tag=attr(s,"control-tag");
  n.id=attr(s,"pitchator-id");n.title=attr(s,"title");
  n.font=attr(s,"font");n.align=attr(s,"text-alignment");
  n.transparent=attr(s,"transparent");
  n.rect=parseRect(attr(s,"origin"),attr(s,"size"));
  n.parent=stack.empty()?-1:stack.back();
  CHECK(n.rect.w>0&&n.rect.h>0);
  CHECK(std::isfinite(n.rect.x)&&std::isfinite(n.rect.y));
  const int index=static_cast<int>(nodes.size());
  nodes.push_back(n);
  const bool selfClosing=!s.empty()&&s.find_last_not_of(" \t\r\n")!=std::string::npos&&
      s[s.find_last_not_of(" \t\r\n")]=='/';
  if(!selfClosing)stack.push_back(index);
 }
 CHECK(stack.empty());CHECK(nodes.size()>=35);
 // A child must fit INSIDE its immediate container, not merely the editor root.
 // This catches clipped controls that still pass flat 1200x620 bounds checks.
 for(const auto& n:nodes){
  if(n.parent<0)continue;
  const auto& p=nodes[static_cast<size_t>(n.parent)];
  CHECK(n.rect.x>=0&&n.rect.y>=0);
  CHECK(n.rect.x+n.rect.w<=p.rect.w+0.001);
  CHECK(n.rect.y+n.rect.h<=p.rect.h+0.001);
 }
 auto find=[&](const char* tag)->int{
  for(size_t i=0;i<nodes.size();++i)if(nodes[i].tag==tag)return static_cast<int>(i);
  return -1;
 };
 auto title=[&](const char* text)->int{
  for(size_t i=0;i<nodes.size();++i)if(nodes[i].title==text)return static_cast<int>(i);
  return -1;
 };
 int logoNode=-1,curve=-1,panel=-1;
 for(size_t i=0;i<nodes.size();++i){
  if(nodes[i].id=="logo")logoNode=static_cast<int>(i);
  if(nodes[i].id=="curve")curve=static_cast<int>(i);
  if(nodes[i].cls=="CViewContainer"&&nodes[i].rect.x==24&&
     nodes[i].rect.y==96)panel=static_cast<int>(i);
 }
 CHECK(logoNode>=0&&curve>=0&&panel>=0);
 CHECK(nodes[logoNode].cls=="CView");
 CHECK(nodes[logoNode].rect.w*0.5==nodes[logoNode].rect.h);
 CHECK(nodes[panel].rect.w==1152&&nodes[panel].rect.h==112);
 int noteId=-1;
 for(size_t i=0;i<nodes.size();++i)
  if(nodes[i].id=="scale-notes")noteId=static_cast<int>(i);
 CHECK(noteId>=0&&nodes[noteId].parent==panel);
 CHECK(nodes[noteId].cls=="CTextLabel"&&nodes[noteId].transparent=="true");
 CHECK(nodes[noteId].font=="Notes");
 CHECK(xml.find("pitchator-id=\"scale-notes\" font=\"Notes\" font-color=\"Text\"")!=std::string::npos);
 CHECK(nodes[noteId].rect.x==16&&nodes[noteId].rect.y==88);
 CHECK(nodes[noteId].rect.w==1122&&nodes[noteId].rect.h==20);
 CHECK(factory.find("syncScaleNotes()")!=std::string::npos);
 CHECK(!collides(absolute(nodes,noteId),absolute(nodes,find("Scale"))));
 // Centering is geometric, and must not conflict with official logo or zoom.
 for(const char* text:{"125A PITCHATOR","MIDI PITCH CURVE SEQUENCER"}){
  int id=title(text);CHECK(id>=0);
  CHECK(std::fabs(absolute(nodes,id).x+nodes[id].rect.w/2.0-600.0)<0.001);
  CHECK(nodes[id].align=="center");
  CHECK(!collides(absolute(nodes,id),absolute(nodes,logoNode)));
  CHECK(!collides(absolute(nodes,id),absolute(nodes,find("UiZoom"))));
 }
 // Every CTextLabel is transparent; dark rectangles behind headings
 // were an unwanted default, not a deliberate part of the 125A GUI.
 for(const auto& node:nodes)
  if(node.cls=="CTextLabel")CHECK(node.transparent=="true");
 struct Group {const char* caption;const char* tag;double x,w;};
 const Group groups[]={{"KEY","Key",16,80},{"SCALE","Scale",114,170},
  {"LENGTH (BARS)","Bars",304,152},{"BEND RANGE (ST)","Range",476,152},
  {"START MODE","Trigger",647,158},{"SCALE LOCK","Lock",817,105},
  {"LOOP","Loop",933,90},{"BYPASS","Bypass",1033,105}};
 double lastEdge=-1;
 for(const auto& g:groups){
  int label=title(g.caption);
  CHECK(label>=0&&nodes[label].parent==panel);
  CHECK(nodes[label].rect.x==g.x&&nodes[label].rect.w==g.w);
  CHECK(nodes[label].rect.y==24&&nodes[label].rect.h==19);
  CHECK(nodes[label].align=="center");
  CHECK(lastEdge==-1||g.x-lastEdge>=10);
  lastEdge=g.x+g.w;
  bool foundControl=false;
  for(const auto& n:nodes)
   if(n.parent==panel&&n.tag==g.tag){
    CHECK(std::fabs(n.rect.y+n.rect.h/2.0-68.0)<0.001);
    foundControl=true;
   }
  CHECK(foundControl);
 }
 CHECK(lastEdge<=1138);
 // All interactive hitboxes must remain separated by at least 4px.
 for(size_t i=0;i<nodes.size();++i){
  if(nodes[i].tag.empty())continue;
  for(size_t j=i+1;j<nodes.size();++j){
   if(nodes[j].tag.empty())continue;
   const auto a=absolute(nodes,i),b=absolute(nodes,j);
   CHECK(!collides(a,b));
  }
 }
 // Check all drawable controls against both 100% and 150% envelopes.
 for(double zoom:{1.0,1.5})
  for(size_t i=0;i<nodes.size();++i){
   const auto r=absolute(nodes,i);
   CHECK(r.x*zoom>=0&&r.y*zoom>=0);
   CHECK((r.x+r.w)*zoom<=1200*zoom+0.001);
   CHECK((r.y+r.h)*zoom<=620*zoom+0.001);
  }
 // Actual VSTGUI nominal font widths vary slightly by OS. Use a conservative
 // ASCII glyph allowance and 16px button padding; no control may crowd text.
 for(const auto& n:nodes){
  if(n.title.empty())continue;
  const bool button=n.cls=="CTextButton";
  const bool label=n.cls=="CTextLabel";
  if(!button&&!label)continue;
  const double glyph=n.font=="Title"?17:n.font=="Section"?11:
     n.font=="Caption"?7.2:7.8;
  const double available=n.rect.w-(button?16.0:0.0);
  CHECK(n.title.size()*glyph<=available);
 }
 // Footer: aligned 32px buttons, 10px gaps and two consistent clusters.
 for(const auto* tag:{"Clear","Delete","Shape","Snap",
                       "AddJump","Previous","Next","GraphZoom"}){
  const int i=find(tag);CHECK(i>=0);
  CHECK(nodes[i].rect.y==556&&nodes[i].rect.h==32);
 }
 CHECK(absolute(nodes,find("PointPosition")).y==520);
 CHECK(absolute(nodes,find("PointPitch")).y==520);
 std::puts("Pitchator UI geometry/text widths/logo/zoom 100-150% PASS");
 return 0;
}
